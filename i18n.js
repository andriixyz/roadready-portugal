export const normalizeLanguage = (language) => language === "ru" ? "ru" : "en";
export const localeFor = (language) => normalizeLanguage(language) === "ru" ? "ru-RU" : "en-GB";
export const TRANSLATIONS = Object.freeze({ en: Object.freeze(EN), ru: Object.freeze(RU) });

export function translate(key, language = "en", values = {}) {
  const table = normalizeLanguage(language) === "ru" ? RU : EN;
  const template = table[key] || EN[key] || key;
  return String(template).replace(/\{(\w+)\}/g, (_match, name) => values[name] ?? "");
}

export function russianPluralKey(count, base) {
  const absolute = Math.abs(Number(count)) % 100;
  const last = absolute % 10;
  if (absolute > 10 && absolute < 20) return `${base}.many`;
  if (last === 1) return `${base}.one`;
  if (last >= 2 && last <= 4) return `${base}.few`;
  return `${base}.many`;
}
